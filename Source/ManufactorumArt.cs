    /// <summary>
    /// Mechanicum manufactorum crafting animation (user 2026-11-21). The building graphic is the forge with the doors shut and no arm;
    /// this draws every frame: the servo arm (rendered work-cycle frames), the forge glow + open mouth while the doors are open, the two
    /// door halves sliding apart (clipped to the mouth like the hangar doors) and the real items: ingredient / product on the depot, in
    /// the claw, or on the belt inside the forge (under the doors).
    ///   LOAD   (a colonist starts the bill): arm takes the ingredient from the depot, doors open as it swings over, sets it on the belt, doors close
    ///   FORGE  doors shut while the work goes on
    ///   UNLOAD (product made, or the work stopped): doors open, the arm (frames backwards) takes it out and puts it on the depot
    /// Timeline steps are 6 ticks (0.1 s at normal speed), the same as the preview GIF (mod assets/buildings/_tools/manufactorum_cycle_preview.py).
    /// Layer positions: ManufactorumArtData.cs (generated by Tools/install_manufactorum_art.py).
    /// </summary>
    [StaticConstructorOnStartup]
    public static class ManufactorumArt
    {
        const string P = "Things/Knights/Manufactorum/Anim/";
        public static readonly Dictionary<string, Material> Mats = new Dictionary<string, Material>();
        static readonly Mesh doorMeshL, doorMeshR;
        static readonly MaterialPropertyBlock mpb = new MaterialPropertyBlock();
        public const int Step = 6, LoadSteps = 32, UnloadSteps = 32, DepotShowTicks = 240;

        static ManufactorumArt()
        {
            foreach (string n in ManufactorumArtData.Layers.Keys) Mats[n] = MaterialPool.MatFrom(P + n, n.StartsWith("candles") ? ShaderDatabase.MoteGlow : ShaderDatabase.Transparent);
            doorMeshL = NewQuad(); doorMeshR = NewQuad();
        }

        static Mesh NewQuad()
        {
            var m = new Mesh();
            m.vertices = new[] { new Vector3(-0.5f, 0f, -0.5f), new Vector3(-0.5f, 0f, 0.5f), new Vector3(0.5f, 0f, 0.5f), new Vector3(0.5f, 0f, -0.5f) };
            m.uv = new[] { new Vector2(0f, 0f), new Vector2(0f, 1f), new Vector2(1f, 1f), new Vector2(1f, 0f) };
            m.triangles = new[] { 0, 1, 2, 0, 2, 3 };
            m.RecalculateNormals(); m.RecalculateBounds();
            return m;
        }

        static float Smooth(float t) { t = Mathf.Clamp01(t); return t * t * (3f - 2f * t); }
        static int Last => ManufactorumArtData.ArmFrames - 1;

        /// <summary>Arm frame, door target and item place for one timeline step. where: 0 none, 1 depot, 2 claw, 3 belt.</summary>
        public static void StepInfo(int state, int k, out int arm, out int doorTarget, out int where)
        {
            bool[] hold = ManufactorumArtData.Holding;
            switch (state)
            {
                case 1:                                                         // LOAD
                    arm = Mathf.Min(k, Last);
                    doorTarget = arm >= 9 && arm <= 21 ? 1 : 0;
                    where = hold[arm] ? 2 : (arm < 8 ? 1 : 3);
                    return;
                case 2: arm = 0; doorTarget = 0; where = 3; return;            // FORGE
                case 3:                                                         // UNLOAD: doors first, then the frames backwards
                    if (k < 6) { arm = Last; doorTarget = 1; where = 3; return; }
                    arm = Last - Mathf.Min(k - 6, Last);
                    doorTarget = arm >= 15 ? 1 : 0;
                    where = hold[arm] ? 2 : (arm > 19 ? 3 : 1);
                    return;
                default: arm = 0; doorTarget = 0; where = 0; return;
            }
        }

        /// <summary>Door amount after s steps of a state (simulated from shut: 1/6 of the travel per step, smoothstep).</summary>
        static float DoorAmount(int state, float s)
        {
            float p = 0f; int n = Mathf.FloorToInt(s);
            for (int k = 0; k <= n; k++)
            {
                StepInfo(state, k, out _, out int tgt, out _);
                float d = (k < n ? 1f : s - n) / 6f;
                p = tgt > p ? Mathf.Min(tgt, p + d) : Mathf.Max(tgt, p - d);
            }
            return Smooth(p);
        }

        static void Quad(Vector3 pic, string name, float alt, Color c)
        {
            float[] r = ManufactorumArtData.Layers[name];
            mpb.SetColor(ShaderPropertyIDs.Color, c);
            Graphics.DrawMesh(MeshPool.plane10, Matrix4x4.TRS(new Vector3(pic.x + r[0], alt, pic.z + r[1]), Quaternion.identity, new Vector3(r[2], 1f, r[3])), Mats[name], 0, null, 0, mpb);
        }

        /// <summary>A door half shifted by dx, clipped to the mouth columns (the part inside the drum plate is not drawn).</summary>
        static void Door(Mesh mesh, Vector3 pic, string name, float alt, float dx)
        {
            float[] r = ManufactorumArtData.Layers[name];
            float x0 = r[0] - r[2] / 2f + dx, x1 = r[0] + r[2] / 2f + dx;
            float c0 = Mathf.Max(x0, ManufactorumArtData.MouthX0), c1 = Mathf.Min(x1, ManufactorumArtData.MouthX1);
            if (c1 - c0 < 0.005f) return;
            float u0 = (c0 - x0) / r[2], u1 = (c1 - x0) / r[2];
            mesh.uv = new[] { new Vector2(u0, 0f), new Vector2(u0, 1f), new Vector2(u1, 1f), new Vector2(u1, 0f) };
            mpb.SetColor(ShaderPropertyIDs.Color, Color.white);
            Graphics.DrawMesh(mesh, Matrix4x4.TRS(new Vector3(pic.x + (c0 + c1) / 2f, alt, pic.z + r[1]), Quaternion.identity, new Vector3(c1 - c0, 1f, r[3])), Mats[name], 0, null, 0, mpb);
        }

        /// <summary>An item's own graphic, fitted into ~0.5 cells, standing on (x, z) (cells from the picture centre).</summary>
        static void Item(Vector3 pic, ThingDef def, float x, float z, float alt)
        {
            Material mat = def?.graphic?.MatSingle;
            if (mat == null) return;
            Vector2 ds = def.graphicData != null ? def.graphicData.drawSize : Vector2.one;
            float k = 0.5f / Mathf.Max(ds.x, ds.y, 0.01f); float w = ds.x * k, h = ds.y * k;
            Graphics.DrawMesh(MeshPool.plane10, Matrix4x4.TRS(new Vector3(pic.x + x, alt, pic.z + z + h * 0.35f), Quaternion.identity, new Vector3(w, 1f, h)), mat, 0);
        }

        public static void Draw(Building_Manufactorum b)
        {
            Vector3 pic = b.TrueCenter() + new Vector3(0f, 0f, ManufactorumArtData.OffZ);
            float alt = AltitudeLayer.BuildingOnTop.AltitudeFor();
            int now = Find.TickManager.TicksGame;
            b.Advance(now);
            float s = (now - b.stateTick) / (float)Step;
            StepInfo(b.state, Mathf.FloorToInt(s), out int arm, out _, out int where);
            float f = b.state == 1 || b.state == 3 ? DoorAmount(b.state, s) : 0f;
            ThingDef item = b.Carried;
            for (int i = 0; ManufactorumArtData.Layers.ContainsKey("candles_" + i); i++)     // candle glow, each cluster on its own flicker
            {
                float fl = CandleFlicker.Value(b.thingIDNumber * 31 + i + 100);
                Quad(pic, "candles_" + i, alt + 0.0005f, new Color(fl, fl, fl, fl));
            }
            if (f > 0.001f)
            {
                Quad(pic, "forge", alt + 0.001f, new Color(1f, 1f, 1f, f));
                Quad(pic, "mouth", alt + 0.002f, Color.white);
                if (where == 3) Item(pic, item, ManufactorumArtData.BeltX, ManufactorumArtData.BeltZ, alt + 0.003f);
                Door(doorMeshL, pic, "doorL", alt + 0.004f, -f * ManufactorumArtData.Slide);
                Door(doorMeshR, pic, "doorR", alt + 0.005f, f * ManufactorumArtData.Slide);
            }
            if (where == 1) Item(pic, item, ManufactorumArtData.DepotX, ManufactorumArtData.DepotZ, alt + 0.006f);
            else if (b.state == 0 && b.depotItem != null && now < b.depotUntil) Item(pic, b.depotItem, ManufactorumArtData.DepotX, ManufactorumArtData.DepotZ, alt + 0.006f);
            Quad(pic, "arm_" + arm.ToString("00"), alt + 0.007f, Color.white);
            if (where == 2) Item(pic, item, ManufactorumArtData.GripX[arm], ManufactorumArtData.GripZ[arm] - 0.12f, alt + 0.008f);
        }
    }

    /// <summary>Mechanicum manufactorum: a normal work table that also runs the crafting animation (see ManufactorumArt).</summary>
    public class Building_Manufactorum : Building_WorkTable
    {
        // animation state only (not saved: after a load the next work tick starts a fresh load cycle)
        public int state, stateTick, lastWorkTick = -9999, depotUntil;
        public ThingDef inDef, outDef, depotItem;
        bool produced;

        /// <summary>What the arm carries right now: the product when unloading a finished item, otherwise the ingredient.</summary>
        public ThingDef Carried => state == 3 && produced ? outDef : inDef;

        public override void UsedThisTick()
        {
            base.UsedThisTick();
            int now = Find.TickManager.TicksGame;
            lastWorkTick = now;
            if (state == 0)
            {
                RecipeDef r = CurrentRecipe();
                inDef = FirstIngredient(r); outDef = r?.ProducedThingDef ?? inDef;
                produced = false; state = 1; stateTick = now; depotItem = null;
            }
        }

        /// <summary>Called when this bench makes its product (GenRecipe patch below).</summary>
        public void Notify_Produced(RecipeDef r)
        {
            if (r?.ProducedThingDef != null) outDef = r.ProducedThingDef;
            produced = true;
            if (state == 2) { state = 3; stateTick = Find.TickManager.TicksGame; }
        }

        public void Advance(int now)
        {
            if (state == 1 && now - stateTick >= ManufactorumArt.LoadSteps * ManufactorumArt.Step) { state = produced ? 3 : 2; stateTick = now; }
            if (state == 2 && now - lastWorkTick > 45) { state = 3; stateTick = now; }           // work stopped: take the ingredient back out
            if (state == 3 && now - stateTick >= ManufactorumArt.UnloadSteps * ManufactorumArt.Step)
            {
                depotItem = Carried; depotUntil = now + ManufactorumArt.DepotShowTicks;
                state = 0; stateTick = now; produced = false;
            }
        }

        RecipeDef CurrentRecipe()
        {
            if (!Spawned) return null;
            foreach (Thing t in InteractionCell.GetThingList(Map))
                if (t is Pawn p && p.CurJob != null && p.CurJob.bill != null && p.CurJob.bill.billStack?.billGiver == this) return p.CurJob.bill.recipe;
            return null;
        }

        static ThingDef FirstIngredient(RecipeDef r)
        {
            if (r == null || r.ingredients.NullOrEmpty()) return null;
            IngredientCount ic = r.ingredients.FirstOrDefault(i => i.IsFixedIngredient) ?? r.ingredients[0];
            return ic.IsFixedIngredient ? ic.FixedIngredient : ic.filter?.AllowedThingDefs.FirstOrDefault();
        }

        protected override void DrawAt(Vector3 drawLoc, bool flip = false)
        {
            ManufactorumArt.Draw(this);           // the building graphic itself is printed in the map mesh
        }
    }

    /// <summary>Tell the manufactorum when it makes its product, so the arm unloads the finished item.</summary>
    [HarmonyPatch(typeof(GenRecipe), nameof(GenRecipe.MakeRecipeProducts))]
    static class Patch_ManufactorumProduced
    {
        static void Postfix(RecipeDef recipeDef, IBillGiver billGiver)
        {
            if (billGiver is Building_Manufactorum m) m.Notify_Produced(recipeDef);
        }
    }
